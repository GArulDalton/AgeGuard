"""Draw the two block diagrams of the paper: Fig. 3 (GNN architecture) and Fig. 4 (recalibration lifecycle)."""
import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch
plt.rcParams.update({'font.family':'DejaVu Sans','font.size':9})
def box(ax,x,y,w,h,t,c,fs=8.5):
    ax.add_patch(FancyBboxPatch((x,y),w,h,boxstyle='round,pad=0.04',fc=c,ec='k',lw=1.1)); ax.text(x+w/2,y+h/2,t,ha='center',va='center',fontsize=fs)
def arr(ax,a,b,ls='-',c='k',rad=0):
    ax.annotate('',b,a,arrowprops=dict(arrowstyle='->',lw=1.3,ls=ls,color=c,connectionstyle=f'arc3,rad={rad}'))
# ---- GNN architecture ----
fig,ax=plt.subplots(figsize=(7.2,3.4)); ax.set_xlim(0,14.4); ax.set_ylim(0,6.8); ax.axis('off')
box(ax,0.05,4.2,2.75,1.6,'Node features\n$x_k^{(0)}=[\\hat g_{kk},\\bar g_{kk},\\rho_k,\\rho_k^2]$','#dfe9f7',6.8)
box(ax,0.05,0.9,2.75,1.6,'Edge features\n$e_{jk}=[\\hat g_{jk},\\hat g_{kj},\\bar g_{jk},\\rho_k,\\rho_j]$','#dfe9f7',6.8)
box(ax,3.25,4.4,1.5,1.2,'Input MLP\n$\\phi_{\\rm in}$','#e8f4e0')
ax.add_patch(FancyBboxPatch((5.1,0.5),5.6,5.6,boxstyle='round,pad=0.05',fc='#fff7e6',ec='#b07d2a',lw=1.2,ls='--'))
ax.text(7.9,5.75,'Message-passing layer  (repeated T times)',ha='center',fontsize=8.5,color='#7a5410')
box(ax,5.4,3.7,2.3,1.4,'Edge message\n$m_{jk}=\\phi_m(z_j,z_k,e_{jk})$','#fde9d9',7.5)
box(ax,8.1,4.35,2.3,0.9,'mean over $j\\neq k$','#f6e3f0',8)
box(ax,8.1,3.25,2.3,0.9,'max over $j\\neq k$','#f6e3f0',8)
box(ax,6.5,1.0,3.5,1.4,'Residual update\n$z_k\\leftarrow z_k+\\phi_u(z_k,\\mathrm{mean},\\mathrm{max})$','#fde9d9',7.5)
box(ax,11.2,3.6,1.5,1.5,'Power head\n$\\sigma(\\phi_{\\rm out})$','#fdf2cc')
box(ax,12.95,3.6,1.35,1.5,'Powers\n$p_k$','#e4e4e4')
arr(ax,(2.85,5.0),(3.25,5.0)); arr(ax,(4.75,5.0),(5.4,4.6)); arr(ax,(2.85,1.7),(5.4,3.9),rad=-0.15)
arr(ax,(7.7,4.6),(8.1,4.8)); arr(ax,(7.7,4.2),(8.1,3.7)); arr(ax,(10.4,4.5),(9.6,2.4),rad=-0.3); arr(ax,(10.4,3.6),(9.2,2.4),rad=-0.2)
arr(ax,(6.6,1.7),(6.0,3.7),rad=0.3,c='#b07d2a'); ax.text(5.2,2.6,'next\nlayer',fontsize=7.5,color='#7a5410')
arr(ax,(10.0,1.7),(11.6,3.6),rad=0.2); arr(ax,(12.7,4.35),(12.95,4.35))
ax.text(7.2,0.15,'Shared weights for all nodes and edges: permutation equivariant and valid for any K',ha='center',fontsize=7.5,style='italic')
plt.tight_layout(); plt.savefig('Fig03_gnn_architecture.png',dpi=300); plt.close()
# ---- recalibration lifecycle ----
fig,ax=plt.subplots(figsize=(7.2,3.6)); ax.set_xlim(0,14.4); ax.set_ylim(0,7.2); ax.axis('off')
box(ax,0.1,5.0,2.6,1.6,'Offline training\n(Algorithm 1)\nfresh simulated\nnetworks','#dfe9f7',7.8)
box(ax,3.3,5.0,2.6,1.6,'Age-aware GNN\npowers $p_k$\n(Algorithm 2)','#e8f4e0',7.8)
box(ax,6.5,5.0,2.8,1.6,'Safety layer\nmodel-based rate\n$A_k=C_{k,(m)}$','#fde9d9',7.8)
box(ax,9.9,5.0,2.0,1.6,'Rate\n$r_k=c\\,A_k$','#fdf2cc',8.5)
box(ax,12.4,5.0,1.9,1.6,'Transmit\nover the\ntrue channel','#e4e4e4',7.8)
box(ax,9.0,2.4,3.2,1.6,'Split conformal\n$\\hat c$ from N observed\ncapacities (Algorithm 3)','#f6d6d6',7.8)
box(ax,9.0,0.2,3.2,1.6,'Online update\n$\\theta_{t+1}=\\theta_t+\\eta(\\varepsilon-e_t)$\n(Algorithm 4)','#f6d6d6',7.8)
box(ax,12.6,1.3,1.7,1.6,'Feedback\nSINR reports /\nACK, NACK','#e4e4e4',7.5)
for a,b in [((2.7,5.8),(3.3,5.8)),((5.9,5.8),(6.5,5.8)),((9.3,5.8),(9.9,5.8)),((11.9,5.8),(12.4,5.8))]: arr(ax,a,b)
arr(ax,(13.35,5.0),(13.45,2.9)); arr(ax,(12.6,2.4),(12.2,3.2)); arr(ax,(12.6,1.8),(12.2,1.0))
arr(ax,(10.6,4.0),(10.9,5.0),c='#b22222'); arr(ax,(9.0,1.0),(10.2,5.0),c='#b22222',rad=-0.35)
ax.text(5.6,3.6,'Propositions 1-2: outage $\\leq\\varepsilon$ if the aging model is correct',fontsize=7.6,ha='center')
ax.text(5.6,3.0,'Proposition 3: outage $\\leq\\varepsilon$ for any channel distribution',fontsize=7.6,ha='center',color='#b22222')
ax.text(5.6,2.4,'Proposition 4: long-run outage $\\to\\varepsilon$ under drift',fontsize=7.6,ha='center',color='#b22222')
plt.tight_layout(); plt.savefig('Fig04_recalibration_lifecycle.png',dpi=300); plt.close(); print('ok')
